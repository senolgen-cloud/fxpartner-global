// Verifies that declared image dimensions match the files on disk.
//
//   node scripts/check-image-dimensions.mjs
//
// src/data/brokers.ts declares a width and height next to every ad creative,
// because next/image needs them to reserve layout space before the file
// loads. Nothing checks that the numbers are true. Swap in a re-exported
// banner at a different size and the page keeps the old numbers: the image
// renders stretched or squashed, and it does it quietly — no error, no
// warning, just a slightly wrong-looking ad that nobody notices for weeks.
//
// The app icons are the same kind of claim and are checked here too. The
// manifest and the <link> tags both state a size next to every icon, and a
// browser trusts the declaration over the file: declare 512x512 for a file
// that is 192 and Android picks it for a splash screen and upscales it.
// There are eight of them across the manifest, the metadata and the service
// worker, they are generated by scripts/build-icons.mjs, and a resize that
// misses one is invisible — a home-screen icon is cached hard, so the only
// symptom is a stale or blurry logo on somebody's phone weeks later.
//
// PNG and JPEG dimensions are read from the file header directly. Neither
// needs a decoder: PNG puts width and height in the IHDR chunk at a fixed
// offset, and JPEG carries them in the SOF marker.

import fs from "node:fs";
import path from "node:path";

const BROKERS = "src/data/brokers.ts";
const PUBLIC = "public";

function pngSize(buf) {
  // 8-byte signature, then IHDR: length(4) type(4) width(4) height(4).
  if (buf.length < 24) return null;
  if (buf.toString("ascii", 12, 16) !== "IHDR") return null;
  return { width: buf.readUInt32BE(16), height: buf.readUInt32BE(20) };
}

function jpegSize(buf) {
  // Walk the marker chain to the first Start-Of-Frame.
  let i = 2;
  while (i < buf.length - 9) {
    if (buf[i] !== 0xff) { i++; continue; }
    const marker = buf[i + 1];
    // SOF0..SOF15, excluding DHT (c4), JPG (c8) and DAC (cc).
    if (marker >= 0xc0 && marker <= 0xcf && marker !== 0xc4 && marker !== 0xc8 && marker !== 0xcc) {
      return { height: buf.readUInt16BE(i + 5), width: buf.readUInt16BE(i + 7) };
    }
    i += 2 + buf.readUInt16BE(i + 2);
  }
  return null;
}

function sizeOf(file) {
  const buf = fs.readFileSync(file);
  if (buf.slice(0, 8).toString("hex") === "89504e470d0a1a0a") return pngSize(buf);
  if (buf[0] === 0xff && buf[1] === 0xd8) return jpegSize(buf);
  return null; // svg, webp, avif — not declared with pixel sizes here
}

const source = fs.readFileSync(BROKERS, "utf8");

// adImage / adImageMobile / adImageTall, each with its own Width and Height.
const VARIANTS = ["adImage", "adImageMobile", "adImageTall"];
const problems = [];
let checked = 0;

for (const variant of VARIANTS) {
  const re = new RegExp(
    `${variant}:\\s*"([^"]+)",[\\s\\S]{0,400}?${variant}Width:\\s*(\\d+),[\\s\\S]{0,200}?${variant}Height:\\s*(\\d+),`,
    "g"
  );
  for (const m of source.matchAll(re)) {
    const [, url, w, h] = m;
    const file = path.join(PUBLIC, url.replace(/^\//, ""));
    if (!fs.existsSync(file)) {
      problems.push({ url, issue: "file does not exist" });
      continue;
    }
    const actual = sizeOf(file);
    if (!actual) continue; // format we cannot measure without a decoder
    checked++;
    if (actual.width !== Number(w) || actual.height !== Number(h)) {
      problems.push({
        url,
        issue: `declared ${w}×${h}, file is ${actual.width}×${actual.height}`,
      });
    }
  }
}

// Blog covers. They carry no declared size — the article frame is square
// and crops whatever it is given — so existence is the whole claim. It is
// worth checking anyway: a cover is referenced by a path in a data file and
// nothing resolves it at build time, so a renamed or deleted file is a
// broken image on a published article and a dead og:image on every share of
// it, with no error anywhere. Renaming one on 2026-08-31 to force social
// platforms to re-scrape is exactly how that mistake gets made.
const BLOG = "src/data/blog.ts";

// The app icons: manifest.json, the Next metadata, and the service worker.
const MANIFEST = "public/manifest.json";
const LAYOUT = "src/app/[locale]/layout.tsx";
const SW = "public/sw.js";

/** One declaration: a public URL, and the size it claims to be (or null). */
function declared(url, sizes, where) {
  const file = path.join(PUBLIC, url.replace(/^\//, ""));
  if (!fs.existsSync(file)) {
    problems.push({ url, issue: `${where} points at a file that does not exist` });
    return;
  }
  if (!sizes) return; // referenced but unsized — existence is the whole claim
  const actual = sizeOf(file);
  if (!actual) return;
  checked++;
  const [w, h] = sizes.split("x").map(Number);
  if (actual.width !== w || actual.height !== h) {
    problems.push({ url, issue: `${where} declares ${w}×${h}, file is ${actual.width}×${actual.height}` });
  }
}

if (fs.existsSync(BLOG)) {
  const covers = [...fs.readFileSync(BLOG, "utf8").matchAll(/coverImage:\s*"([^"]+)"/g)];
  if (covers.length === 0) problems.push({ url: BLOG, issue: "declares no covers — has the file changed shape?" });
  for (const [, url] of covers) declared(url, null, "a blog post");
} else {
  problems.push({ url: BLOG, issue: "is missing" });
}

if (fs.existsSync(MANIFEST)) {
  const manifest = JSON.parse(fs.readFileSync(MANIFEST, "utf8"));
  if (!manifest.icons?.length) problems.push({ url: MANIFEST, issue: "declares no icons" });
  for (const icon of manifest.icons ?? []) declared(icon.src, icon.sizes, "manifest.json");
  // Android needs a maskable icon; without one it puts the full-bleed
  // square on a white plate and crops it to the launcher's shape.
  if (!(manifest.icons ?? []).some((i) => (i.purpose ?? "").includes("maskable"))) {
    problems.push({ url: MANIFEST, issue: "has no maskable icon — Android will crop the full-bleed one" });
  }
} else {
  problems.push({ url: MANIFEST, issue: "is missing" });
}

if (fs.existsSync(LAYOUT)) {
  const layout = fs.readFileSync(LAYOUT, "utf8");
  const block = layout.slice(layout.indexOf("icons: {"), layout.indexOf("icons: {") + 900);
  const entries = [...block.matchAll(/url:\s*"([^"]+)"(?:[^}]*?sizes:\s*"(\d+x\d+)")?/g)];
  if (entries.length === 0) problems.push({ url: LAYOUT, issue: "declares no icons" });
  for (const [, url, sizes] of entries) declared(url, sizes, "layout metadata");
} else {
  problems.push({ url: LAYOUT, issue: "is missing" });
}

if (fs.existsSync(SW)) {
  for (const [, url] of fs.readFileSync(SW, "utf8").matchAll(/icon:\s*"(\/[^"]+)"/g)) {
    declared(url, null, "the service worker's notification");
  }
}

if (!problems.length) {
  console.log(`every declared image size matches the file (${checked} checked)`);
  process.exit(0);
}

console.error(`${problems.length} image(s) declared at the wrong size:\n`);
for (const p of problems) {
  console.error(`  ${p.url}`);
  console.error(`    ${p.issue}\n`);
}
process.exit(1);
